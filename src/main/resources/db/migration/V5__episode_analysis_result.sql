-- 통합 분석(2.4, Manyfast F-ZSPZHH) 결과 카드(3.1, F-HGUJDZ) 영속화. V1~V4는 수정하지 않는다.
-- Episode 하위 서브도메인 고유 데이터라 episode_id/account_id 값 참조만 쓴다(FK 없음, 기존 관례와 동일).
-- Episode당 결과는 하나만 존재한다.
--
-- 카드 3장 중 실제 값을 가진 첫 번째 카드(WITHHELD/DISCONTINUE/DO_MORE_TODAY)만 저장한다 — 두 번째
-- (CONTINUE_USE)/세 번째(HOSPITAL_VISIT) 카드는 ResultCardAssembler가 항상 빈 내용으로 만든다.
-- evidence_* 컬럼은 causeType에 따라 셋 중 하나만 채워지는 union 형태다(PRODUCT=Timing, COMBINATION=
-- Combination, SLEEP/WEATHER=Frequency).

CREATE TABLE episode_analysis_result (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6),
    episode_id  BIGINT NOT NULL,
    account_id  BIGINT NOT NULL,
    hold        BOOLEAN NOT NULL,
    hold_reason VARCHAR(255),
    confidence  VARCHAR(255),
    card_type   VARCHAR(255) NOT NULL,
    cause_type  VARCHAR(255),
    coverage_days BIGINT,
    evidence_product_id BIGINT,
    evidence_usage_start_date DATE,
    evidence_symptom_start_date DATE,
    evidence_tag_a VARCHAR(255),
    evidence_tag_b VARCHAR(255),
    evidence_conflict_placement VARCHAR(255),
    evidence_observation_count INTEGER,
    evidence_matched_observation_count INTEGER,
    CONSTRAINT uk_episode_analysis_result_episode UNIQUE (episode_id),
    CONSTRAINT episode_analysis_result_hold_reason_check
        CHECK (hold_reason IN ('NO_TARGET', 'INSUFFICIENT_RECORDS', 'INCONCLUSIVE_EVIDENCE') OR hold_reason IS NULL),
    CONSTRAINT episode_analysis_result_confidence_check
        CHECK (confidence IN ('HIGH', 'NORMAL') OR confidence IS NULL),
    CONSTRAINT episode_analysis_result_card_type_check
        CHECK (card_type IN ('WITHHELD', 'DISCONTINUE', 'DO_MORE_TODAY')),
    CONSTRAINT episode_analysis_result_cause_type_check
        CHECK (cause_type IN ('PRODUCT', 'COMBINATION', 'SLEEP', 'WEATHER') OR cause_type IS NULL),
    CONSTRAINT episode_analysis_result_conflict_placement_check
        CHECK (evidence_conflict_placement IN ('SAME_TIME_SLOT', 'SPLIT_AM_PM', 'NONE') OR evidence_conflict_placement IS NULL)
);
